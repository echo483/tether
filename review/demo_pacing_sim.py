#!/usr/bin/env python3
"""Demo-pacing arithmetic for TETHER (review artefact, not project code).

Question this answers: what will a judge actually SEE, second by second, during the
squeeze -> TETHER-on -> blackout beats, and how long is the dead air between them?

Model: illustrative PX4-like stream mix (REPLACE WITH TONIGHT'S CENSUS) -> one FIFO,
drop-tail queue of K bytes -> link of capacity C bytes/s -> ground. Byte-granular
service. Ground computes Age of Information (AoI) of ATTITUDE at 10 ms resolution and
the largest HEARTBEAT gap. Stdlib only, deterministic (phases fixed by seed).
"""
import random
from collections import deque

OVH = 12  # MAVLink2 header(10)+CRC(2), unsigned
# name: (Hz, payload bytes, critical?)  -- illustrative, NOT measured
MIX = {
    "HEARTBEAT": (1, 9, True), "SYS_STATUS": (1, 43, True),
    "ATTITUDE": (20, 28, True), "GLOBAL_POSITION_INT": (5, 28, True),
    "BATTERY_STATUS": (0.5, 54, True), "EXTENDED_SYS_STATE": (1, 2, True),
    "ATTITUDE_QUATERNION": (10, 48, False), "LOCAL_POSITION_NED": (10, 28, False),
    "VFR_HUD": (4, 20, False), "GPS_RAW_INT": (5, 52, False),
    "HIGHRES_IMU": (50, 63, False), "SERVO_OUTPUT_RAW": (10, 37, False),
    "RC_CHANNELS": (5, 42, False), "ATTITUDE_TARGET": (10, 37, False),
    "POSITION_TARGET_LOCAL_NED": (10, 51, False), "ESTIMATOR_STATUS": (2, 42, False),
    "VIBRATION": (2, 32, False), "ALTITUDE": (10, 32, False),
}
L_TOT = sum(hz * (p + OVH) for hz, p, _ in MIX.values())
L_CRIT = sum(hz * (p + OVH) for hz, p, c in MIX.values() if c)


def gen(t0, t1, seed, shed_after=None):
    """Messages generated by the autopilot. Non-critical streams stop at shed_after."""
    rnd = random.Random(seed)
    out = []
    for name, (hz, p, crit) in MIX.items():
        per, t = 1.0 / hz, t0 + rnd.random() / hz
        while t < t1:
            if crit or shed_after is None or t < shed_after:
                out.append((t, name, p + OVH))
            t += per
    out.sort()
    return out


def run(C_hi, C_lo, t_sq, K, T, seed, shed_at=None, purge=False,
        blackout=None, lvw=False, dt=0.001):
    """Return (aoi samples [(t, age)], heartbeat rx times)."""
    msgs = deque(gen(0, T, seed, shed_after=shed_at))
    q, qbytes, rem = deque(), 0, 0.0   # queue of (t_gen, name, size)
    last_att, hb, aoi = None, [], []
    t, purged = 0.0, False
    while t < T:
        while msgs and msgs[0][0] <= t:
            m = msgs.popleft()
            if lvw:  # latest-value-wins: one slot per msgid
                for i, x in enumerate(q):
                    if x[1] == m[1] and i > 0:
                        qbytes -= x[2]; del q[i]; break
            if qbytes + m[2] <= K:
                q.append(m); qbytes += m[2]
        if purge and shed_at is not None and t >= shed_at and not purged:
            keep = deque(x for x in q if MIX[x[1]][2]); purged = True; rem = 0.0
            qbytes = sum(x[2] for x in keep); q = keep
        up = not (blackout and blackout[0] <= t < blackout[1])
        cap = (C_lo if t >= t_sq else C_hi) * dt if up else 0.0
        while q and cap > 0:
            need = q[0][2] - rem
            if cap >= need:
                cap -= need; rem = 0.0
                tg, name, sz = q.popleft(); qbytes -= sz
                if name == "ATTITUDE":
                    last_att = tg if last_att is None else max(last_att, tg)
                if name == "HEARTBEAT":
                    hb.append(t)
            else:
                rem += cap; cap = 0
        if round(t / dt) % 10 == 0 and last_att is not None:
            aoi.append((t, t - last_att))
        t += dt
    return aoi, hb


def first(aoi, t_from, pred):
    for t, a in aoi:
        if t >= t_from and pred(a):
            return t
    return None


def stats(aoi, a, b):
    xs = sorted(v for t, v in aoi if a <= t < b)
    return xs[len(xs) // 2], xs[int(0.99 * (len(xs) - 1))], xs[-1]


def maxgap(hb, a, b):
    ts = [a] + [x for x in hb if a <= x < b] + [b]
    return max(y - x for x, y in zip(ts, ts[1:]))


if __name__ == "__main__":
    print(f"illustrative mix: L_total={L_TOT/1e3:.2f} kB/s  L_crit={L_CRIT/1e3:.2f} kB/s")
    C_HI, C_LO, T_SQ, T = 100e3, 2.0e3, 5.0, 60.0
    print(f"squeeze: C {C_HI/1e3:.0f} -> {C_LO/1e3:.1f} kB/s at t={T_SQ}s, "
          f"fluid stale-growth (L-C)/C = {(L_TOT-C_LO)/C_LO:.1f} s per s\n")
    for Ks in (0.5, 3.0, 20.0):
        K = Ks * C_LO
        print(f"--- queue K = {Ks:.1f} s x C = {K/1e3:.1f} kB  (stale cap K/C = {Ks:.1f} s)")
        aoi, hb = run(C_HI, C_LO, T_SQ, K, 40, 1)
        t1 = first(aoi, T_SQ, lambda a: a > 1.0)
        p50, p99, mx = stats(aoi, T_SQ + 10, 40)
        print(f"  UNMANAGED: AoI>1s after {('%.1fs' % (t1 - T_SQ)) if t1 else 'never'}; "
              f"steady AoI p50={p50:.2f}s p99={p99:.2f}s; max HB gap={maxgap(hb, T_SQ, 40):.1f}s")
        t_on = T_SQ + 10.0
        for purge in (False, True):
            aoi, hb = run(C_HI, C_LO, T_SQ, K, 40, 1, shed_at=t_on, purge=purge)
            tr = first(aoi, t_on, lambda a: a < 0.3)
            p50, p99, mx = stats(aoi, t_on + 10, 40)
            lab = "511 + purge queue" if purge else "511 only        "
            print(f"  TETHER {lab}: fresh (<0.3s) {('%.1fs' % (tr - t_on)) if tr else 'never'} "
                  f"after ON; steady p50={p50:.3f}s p99={p99:.3f}s")
    print("\n--- blackout 8 s while managed (critical-only flowing), K = 20 s x C")
    K, t_on, bo = 20 * C_LO, T_SQ, (20.0, 28.0)
    for lvw in (False, True):
        aoi, hb = run(C_HI, C_LO, T_SQ, K, 60, 1, shed_at=t_on, blackout=bo, lvw=lvw)
        tr = first(aoi, bo[1], lambda a: a < 0.3)
        lab = "latest-value-wins" if lvw else "FIFO store+replay"
        print(f"  {lab}: picture fresh {('%.1fs' % (tr - bo[1])) if tr else 'never'} after link returns")
    drain = 8 * L_CRIT / (C_LO - L_CRIT)
    print(f"  fluid check, FIFO replay drain = 8 s x L_crit / (C - L_crit) = {drain:.1f} s")
    # i.i.d. loss: does QGC visibly 'fall apart' at 20%?  P(>=k consecutive HB lost)
    print("\n--- spec profile: 20% iid loss, 1 Hz heartbeat, 120 s demo")
    for k in (3, 4):
        n = 120 - k + 1
        print(f"  P(at least one run of {k} lost heartbeats in 120 s) ~ "
              f"{1 - (1 - 0.8 * 0.2**k) ** n:.2f}")
